def new_config(args: argparse.Namespace) -> dict:
    return {
        "version": 1,
        "profile": args.profile or "standard",
        "ui": args.ui,
        "brief": args.brief,
        "assessment": args.assessment,
        "board": {"tool": args.board or "local"},
        "branches": {"integration": "main" if args.trunk else "dev", "release": "main", "story": "feat/us-{id}-{slug}"},
        "sprint": {"length": normalize_sprint_length(args.sprint_length or "1 day"), "current": 1},
        "wip_limit": 2,
        "checkpoints": args.checkpoints or "every-step",
        "viewports": [390, 1024, 1280] if args.ui else [],
        "freeze": {"release": False},
    }


def update_config(config: dict, args: argparse.Namespace) -> List[str]:
    """Apply flags given on a re-run of init. Returns the changes made."""
    changes: List[str] = []
    if args.profile and args.profile != config.get("profile"):
        changes.append(f"profile {config.get('profile')} -> {args.profile}")
        config["profile"] = args.profile
    for flag in ("ui", "brief", "assessment"):
        if getattr(args, flag) and not config.get(flag):
            changes.append(f"{flag} on")
            config[flag] = True
    if args.ui and not config.get("viewports"):
        config["viewports"] = [390, 1024, 1280]
    board = config.setdefault("board", {})
    if args.board and args.board != board.get("tool"):
        changes.append(f"board {board.get('tool')} -> {args.board} (board identifiers kept; update them by hand)")
        board["tool"] = args.board
    branches = config.setdefault("branches", {})
    if args.trunk and branches.get("integration") != "main":
        changes.append(f"integration branch {branches.get('integration')} -> main (trunk-based)")
        branches["integration"] = "main"
    if args.checkpoints and args.checkpoints != config.get("checkpoints", "every-step"):
        changes.append(f"checkpoints {config.get('checkpoints', 'every-step')} -> {args.checkpoints}")
        config["checkpoints"] = args.checkpoints
    sprint = config.setdefault("sprint", {})
    if args.sprint_length:
        length = normalize_sprint_length(args.sprint_length)
        if length != sprint.get("length"):
            changes.append(f"sprint length {sprint.get('length')} -> {length}")
            sprint["length"] = length
    return changes


def cmd_init(args: argparse.Namespace) -> int:
    root = Path(args.dir).resolve()
    config_path = root / CONFIG_NAME
    if config_path.exists():
        config = load_config(root) or {}
        changes = update_config(config, args)
        if changes:
            config_path.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
            print(f"updated  {CONFIG_NAME}: {'; '.join(changes)}")
        else:
            print(f"{CONFIG_NAME} exists; keeping it. Creating any missing documents for profile '{config.get('profile')}'.")
    else:
        config = new_config(args)
        config_path.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
        print(f"created  {CONFIG_NAME}")

    docs = required_docs(config)
    for relative, template in docs:
        target = root / relative
        if template is None:
            existed = target.exists()
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(docs_index(docs, target.read_text(encoding="utf-8") if existed else ""), encoding="utf-8")
            print(f"{'updated ' if existed else 'created '} {relative}")
            continue
        if target.exists():
            print(f"exists   {relative}")
            continue
        source = TEMPLATES / template
        if not source.is_file():
            print(f"missing template {template}; skipped {relative}", file=sys.stderr)
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(source.read_text(encoding="utf-8"), encoding="utf-8")
        print(f"created  {relative}")
    print("\nNext: fill the TODO(whole-team) markers, add the working agreement (wt.py agreement), connect the board.")
    return 0


def next_story(stories: Sequence[Story]) -> Tuple[Optional[Story], List[Tuple[Story, List[str]]]]:
    by_id = {story.id: story for story in stories}
    rank = {priority: index for index, priority in enumerate(PRIORITIES)}
    candidates: List[Story] = []
    blocked: List[Tuple[Story, List[str]]] = []
    for story in stories:
        if story.status != "Not started" or story.priority == "DEFERRED" or story.sprint_number == float("inf"):
            continue  # backlog stories are pulled only through sprint planning
        waiting = [dep for dep in story.depends if by_id.get(dep) is None or by_id[dep].status != "Done"]
        if waiting:
            blocked.append((story, waiting))
        else:
            candidates.append(story)
    candidates.sort(key=lambda s: (s.sprint_number, rank.get(s.priority or "", 9), int(s.id.split("-")[1])))
    return (candidates[0] if candidates else None), blocked


def placeholder_counts(root: Path, docs: Sequence[Tuple[str, Optional[str]]]) -> Dict[str, int]:
    counts: Dict[str, int] = {}
    for relative, _ in docs:
        text = read(root, relative)
        if text and PLACEHOLDER in text:
            counts[relative] = text.count(PLACEHOLDER)
    return counts


def open_handover(root: Path) -> Optional[str]:
    text = read(root, "CHANGELOG.md") or ""
    for line in text.splitlines():
        stripped = line.strip().lstrip("-* ").strip()
        if stripped.lower().startswith("handover") and "(resolved)" not in stripped.lower():
            return stripped
    return None


def open_retro_actions(root: Path) -> int:
    """Unchecked action items in the retrospectives, outside the template comment."""
    text = read(root, RETROS_PATH) or ""
    text = re.sub(r"<!--.*?-->", "", text, flags=re.DOTALL)
    return len(re.findall(r"^\s*-\s*\[ \]\s*\S", text, re.MULTILINE))


def cmd_status(args: argparse.Namespace) -> int:
    root = find_root(Path.cwd())
    config = load_config(root)
    if config is None:
        print(f"No {CONFIG_NAME} in {root}. Start with intake (reference/intake.md), then run: wt.py init --profile <lite|standard|strict>")
        return 0
    board = config.get("board", {}).get("tool", "local")
    sprint = config.get("sprint", {}).get("current", "?")
    frozen = " · release branch FROZEN" if config.get("freeze", {}).get("release") else ""
    checkpoints = config.get("checkpoints", "every-step")
    print(f"whole-team · profile {config.get('profile')} · board {board} · sprint {sprint} · checkpoints {checkpoints}{frozen}")

    text = read(root, STORIES_PATH)
    if text is None:
        print(f"No {STORIES_PATH} yet.")
        return 0
    stories = parse_stories(text)
    counts = {status: 0 for status in STATUSES}
    for story in stories:
        if story.status in counts:
            counts[story.status] += 1
    summary = " · ".join(f"{name} {count}" for name, count in counts.items() if count)
    print(f"Stories: {len(stories)} total" + (f" · {summary}" if summary else ""))
    musts = [s for s in stories if s.priority == "MUST" and s.status != "Dropped"]
    if musts:
        done = sum(1 for s in musts if s.status == "Done")
        print(f"MUST done: {done}/{len(musts)}")

    in_sprint = [s for s in stories if s.in_sprint(sprint) and s.status != "Dropped"]
    if in_sprint:
        done = sum(1 for s in in_sprint if s.status == "Done")
        print(f"Sprint {sprint}: {done}/{len(in_sprint)} stories done")

    active = [s for s in stories if s.status in ("In progress", "In review")]
    limit = int(config.get("wip_limit", 2))
    for story in active:
        print(f"{story.status}: {story.id} {story.short_title}")
    if len(active) > limit:
        print(f"WIP {len(active)} is over the limit of {limit}: finish before starting another.")

    upcoming, blocked = next_story(stories)
    if upcoming:
        print(f"Next up: {upcoming.id} {upcoming.short_title} (sprint {upcoming.sprint}, {upcoming.priority})")
    elif not active:
        print("Next up: nothing ready. Plan the next stories or close the sprint.")
    for story, waiting in blocked:
        print(f"Blocked: {story.id} waits on {', '.join(waiting)}")

    handover = open_handover(root)
    if handover:
        print(f"Handover: {handover}")
    actions = open_retro_actions(root)
    if actions:
        print(f"Retro actions open: {actions} (check them at sprint planning)")
    placeholders = placeholder_counts(root, required_docs(config))
    if placeholders:
        total = sum(placeholders.values())
        print(f"Docs: {total} placeholder(s) to fill in {len(placeholders)} file(s)")
    return 0


def lint(root: Path, config: dict, release: bool) -> Tuple[List[str], List[str]]:
    errors: List[str] = []
    warnings: List[str] = []
    docs = required_docs(config)
    for relative, _ in docs:
        if not (root / relative).exists():
            errors.append(f"{relative}: missing (required by profile '{config.get('profile')}'); run wt.py init")

    text = read(root, STORIES_PATH)
    stories = parse_stories(text) if text else []
    by_id: Dict[str, Story] = {}
    for story in stories:
        where = f"{STORIES_PATH}:{story.line} {story.id}"
        if story.id in by_id:
            errors.append(f"{where}: duplicate ID (first at line {by_id[story.id].line})")
            continue
        by_id[story.id] = story
        if not STORY_SHAPE.match(story.title):
            warnings.append(f"{where}: title is not 'As a <persona>, I want <capability>, so that <value>.'")
        if not story.has_criteria:
            errors.append(f"{where}: no acceptance criteria")
        hint = " (separate fields with ' · ', for example 'Priority: MUST · Sprint: 1 · Status: Not started')"
        if story.priority not in PRIORITIES:
            extra = hint if story.priority and ("," in story.priority or ":" in story.priority) else ""
            errors.append(f"{where}: priority '{story.priority}' is not one of {', '.join(PRIORITIES)}{extra}")
        if story.status not in STATUSES:
            extra = hint if story.status and ("," in story.status or ":" in story.status) else ""
            errors.append(f"{where}: status '{story.status}' is not one of {', '.join(STATUSES)}{extra}")
        if story.status == "Done" and not story.tests:
            errors.append(f"{where}: Done but the Tests line is empty")

    for story in by_id.values():
        where = f"{STORIES_PATH}:{story.line} {story.id}"
        for dep in story.depends:
            if dep == story.id:
                errors.append(f"{where}: depends on itself")
            elif dep not in by_id:
                errors.append(f"{where}: depends on unknown {dep}")
            elif story.status == "Done" and by_id[dep].status != "Done":
                errors.append(f"{where}: Done but its dependency {dep} is {by_id[dep].status}")
    for cycle in dependency_cycles(by_id):
        errors.append(f"{STORIES_PATH}: dependency cycle {' -> '.join(cycle)}; no story in it can start")

    limit = int(config.get("wip_limit", 2))
    active = [s.id for s in by_id.values() if s.status in ("In progress", "In review")]
    if len(active) > limit:
        warnings.append(f"WIP {len(active)} ({', '.join(active)}) is over the limit of {limit}")

    requirements_text = read(root, REQUIREMENTS_PATH)
    if requirements_text is not None:
        defined = parse_requirements(requirements_text)
        used = set()
        for story in by_id.values():
            for req in story.requirements:
                if req not in defined:
                    errors.append(f"{STORIES_PATH}:{story.line} {story.id}: references {req}, not defined in {REQUIREMENTS_PATH}")
                if story.status != "Dropped":
                    used.add(req)
        for req, active_req in defined.items():
            if active_req and req not in used:
                message = f"{REQUIREMENTS_PATH}: {req} is not covered by any story"
                (errors if release else warnings).append(message)

    for relative, count in placeholder_counts(root, docs).items():
        message = f"{relative}: {count} {PLACEHOLDER} placeholder(s) left"
        (errors if release else warnings).append(message)

    changelog = read(root, "CHANGELOG.md") or ""
    if re.search(r"board sync pending", changelog, re.IGNORECASE):
        message = "CHANGELOG.md: 'Board sync pending' entry not cleared"
        (errors if release else warnings).append(message)

    if release:
        for story in by_id.values():
            if story.priority == "MUST" and story.status not in ("Done", "Dropped"):
                errors.append(f"{story.id}: MUST story is {story.status}")
            elif story.status in ("In progress", "In review"):
                errors.append(f"{story.id}: {story.status} at release")
        if open_handover(root):
            errors.append("CHANGELOG.md: open Handover line; finish the work or mark it (resolved)")
    return errors, warnings


def cmd_lint(args: argparse.Namespace) -> int:
    root = find_root(Path.cwd())
    config = load_config(root)
    if config is None:
        print(f"error: no {CONFIG_NAME} found; run wt.py init first")
        return 1
    errors, warnings = lint(root, config, args.release)
    for message in errors:
        print(f"error    {message}")
    for message in warnings:
        print(f"warning  {message}")
    mode = "release lint" if args.release else "lint"
    print(f"{mode}: {len(errors)} error(s), {len(warnings)} warning(s)")
    return 1 if errors else 0


def cmd_kanban(args: argparse.Namespace) -> int:
    root = find_root(Path.cwd())
    text = read(root, STORIES_PATH)
    if text is None:
        print(f"error: {STORIES_PATH} not found")
        return 1
    stories = parse_stories(text)
    today = _dt.date.today().isoformat()
    lines = [
        "# Kanban",
        "",
        f"Generated by `wt.py kanban` from `USER_STORIES.md` on {today}. Do not edit by hand.",
    ]
    for status in STATUSES:
        column = [s for s in stories if s.status == status]
        lines += ["", f"## {status} ({len(column)})", ""]
        for story in sorted(column, key=lambda s: (s.sprint_number, int(s.id.split("-")[1]))):
            lines.append(f"- **{story.id}** {story.short_title} · {story.priority} · Sprint {story.sprint}")
    unknown = [s for s in stories if s.status not in STATUSES]
    if unknown:
        lines += ["", f"## Unknown status ({len(unknown)})", ""]
        lines += [f"- **{s.id}** {s.short_title} · status '{s.status}'" for s in unknown]
    target = root / KANBAN_PATH
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {KANBAN_PATH} ({len(stories)} stories)")
    return 0


def cmd_sprint(args: argparse.Namespace) -> int:
    root = find_root(Path.cwd())
    config = load_config(root) or {}
    number = str(args.number if args.number is not None else config.get("sprint", {}).get("current", 1))
    text = read(root, STORIES_PATH)
    if text is None:
        print(f"error: {STORIES_PATH} not found")
        return 1
    stories = [s for s in parse_stories(text) if s.in_sprint(number)]
    planned = [s for s in stories if s.status != "Dropped"]
    shipped = [s for s in planned if s.status == "Done"]
    open_ = [s for s in planned if s.status != "Done"]
    dropped = [s for s in stories if s.status == "Dropped"]
    print(f"Sprint {number}: planned {len(planned)} · done {len(shipped)} · not done {len(open_)} · dropped {len(dropped)}")
    print("\nShipped")
    print("\n".join(f"- {s.id} {s.short_title}" for s in shipped) or "- none")
    print("\nNot done (slip to the next sprint with a reason, or keep In progress on its branch)")
    print("\n".join(f"- {s.id} {s.short_title} ({s.status})" for s in open_) or "- none")
    if dropped:
        print("\nDropped")
        print("\n".join(f"- {s.id} {s.short_title}" for s in dropped))
    return 0


def cmd_agreement(args: argparse.Namespace) -> int:
    root = find_root(Path.cwd())
    config = load_config(root)
    if config is None:
        print(f"error: no {CONFIG_NAME} found; run wt.py init first")
        return 1
    branches = config.get("branches", {})
    template = (TEMPLATES / "WORKING_AGREEMENT.md").read_text(encoding="utf-8")
    values = {
        "profile": config.get("profile", "standard"),
        "board": config.get("board", {}).get("tool", "local"),
        "sprint_length": config.get("sprint", {}).get("length", "1 day"),
        "wip_limit": config.get("wip_limit", 2),
        "checkpoints": config.get("checkpoints", "every-step"),
        "story_branch": branches.get("story", "feat/us-{id}-{slug}"),
        "integration": branches.get("integration", "dev"),
        "release": branches.get("release", "main"),
    }
    for key, value in values.items():
        template = template.replace("{" + key + "}", str(value))
    print(template, end="")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="wt.py", description="whole-team project helper")
    sub = parser.add_subparsers(dest="command", required=True)

    init = sub.add_parser("init", help="create config and the profile's documents")
    init.add_argument("--profile", choices=PROFILES, default=None, help="default: standard (on an existing project: change profile)")
    init.add_argument("--board", choices=BOARDS, default=None, help="default: local")
    init.add_argument("--ui", action="store_true", help="the project has screens")
    init.add_argument("--brief", action="store_true", help="work starts from a brief or spec")
    init.add_argument("--assessment", action="store_true", help="assessment or take-home: brief, traceability, AI usage")
    init.add_argument("--trunk", action="store_true", help="trunk-based: story branches merge into main")
    init.add_argument("--checkpoints", choices=CHECKPOINTS, default=None, help="when the agent stops to ask: every-step (default), phase or gates")
    init.add_argument("--sprint-length", default=None, help='for example "1 day", "1 week", "2 weeks" (a bare number means days); default: 1 day')
    init.add_argument("--dir", default=".")
    init.set_defaults(func=cmd_init)

    sub.add_parser("status", help="where the project stands").set_defaults(func=cmd_status)
    lint_parser = sub.add_parser("lint", help="check stories, coverage and documents")
    lint_parser.add_argument("--release", action="store_true", help="release gate: stricter")
    lint_parser.set_defaults(func=cmd_lint)
    sub.add_parser("kanban", help="write KANBAN.md").set_defaults(func=cmd_kanban)
    sprint_parser = sub.add_parser("sprint", help="sprint report: planned, shipped, not done")
    sprint_parser.add_argument("number", nargs="?", type=int, help="default: the current sprint")
    sprint_parser.set_defaults(func=cmd_sprint)
    sub.add_parser("agreement", help="print the working agreement block").set_defaults(func=cmd_agreement)
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    args = build_parser().parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
