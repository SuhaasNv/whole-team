STORY_HEADING = re.compile(r"^###\s+(US-\d+)\s*:\s*(.+?)\s*$")
EPIC_HEADING = re.compile(r"^##\s+(?!#)(.+?)\s*$")
STORY_ID = re.compile(r"\bUS-\d+\b")
REQ_ID = re.compile(r"\b[A-Z]{2,4}-\d{3}\b")
REQ_ROW = re.compile(r"^\|\s*([A-Z]{2,4}-\d{3})\s*\|")
REQ_HEADING = re.compile(r"^#{2,4}\s+([A-Z]{2,4}-\d{3})\b")
STORY_SHAPE = re.compile(r"^As an? .+?, I want .+?, so that .+", re.IGNORECASE)
FENCE = re.compile(r"^\s*(```|~~~)")
FIELD_END = r"(?=\s*[·|]|\s*$)"


def field_value(block: str, name: str) -> Optional[str]:
    match = re.search(rf"{name}:[ \t]*(.*?){FIELD_END}", block, re.MULTILINE)
    return match.group(1).strip() if match else None


@dataclass
class Story:
    id: str
    title: str
    epic: str
    line: int
    priority: Optional[str] = None
    sprint: Optional[str] = None
    status: Optional[str] = None
    depends: List[str] = field(default_factory=list)
    requirements: List[str] = field(default_factory=list)
    tests: Optional[str] = None
    has_criteria: bool = False

    @property
    def sprint_number(self) -> float:
        try:
            return float(self.sprint or "")
        except ValueError:
            return float("inf")

    def in_sprint(self, number: object) -> bool:
        """True when this story's sprint equals `number`, so "01", "1" and 1.0 all match sprint 1."""
        try:
            return self.sprint_number == float(str(number))
        except ValueError:
            return False

    @property
    def short_title(self) -> str:
        match = re.search(r"I want (?:to )?(.+?), so that", self.title, re.IGNORECASE)
        return match.group(1) if match else self.title


def dependency_cycles(by_id: Dict[str, Story]) -> List[List[str]]:
    """Each dependency cycle once, as a path that ends where it starts (US-001 -> US-002 -> US-001)."""
    cycles: List[List[str]] = []
    done: set = set()

    def visit(story_id: str, stack: List[str]) -> None:
        if story_id in stack:
            cycles.append(stack[stack.index(story_id):] + [story_id])
            return
        if story_id in done or story_id not in by_id:
            return
        stack.append(story_id)
        for dep in by_id[story_id].depends:
            if dep != story_id:
                visit(dep, stack)
        stack.pop()
        done.add(story_id)

    for story_id in by_id:
        visit(story_id, [])
    return cycles


def parse_stories(text: str) -> List[Story]:
    stories: List[Story] = []
    epic = ""
    current: Optional[Story] = None
    block: List[str] = []

    def finish() -> None:
        if current is None:
            return
        body = "\n".join(block)
        current.priority = field_value(body, "Priority")
        current.sprint = field_value(body, "Sprint")
        current.status = field_value(body, "Status")
        depends = field_value(body, "Depends on") or ""
        current.depends = STORY_ID.findall(depends)
        reqs = field_value(body, "Requirements") or ""
        current.requirements = REQ_ID.findall(reqs)
        tests = re.search(r"^\s*-\s*Tests:[ \t]*(.*)$", body, re.MULTILINE)
        current.tests = tests.group(1).strip() if tests else None
        criteria = re.search(
            r"^\s*-\s*Acceptance criteria:[ \t]*(.*?)(?=^\s*-\s*Priority:|\Z)",
            body,
            re.MULTILINE | re.DOTALL,
        )
        if criteria:
            content = re.sub(r"[\s\-*]", "", criteria.group(1))
            current.has_criteria = bool(content)
        stories.append(current)

    in_fence = False
    for number, line in enumerate(text.splitlines(), start=1):
        if FENCE.match(line):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        heading = STORY_HEADING.match(line)
        if heading:
            finish()
            current = Story(id=heading.group(1), title=heading.group(2), epic=epic, line=number)
            block = []
            continue
        epic_match = EPIC_HEADING.match(line)
        if epic_match:
            finish()
            current = None
            block = []
            epic = epic_match.group(1)
            continue
        if current is not None:
            block.append(line)
    finish()
    return stories


def parse_requirements(text: str) -> Dict[str, bool]:
    """Map requirement ID to whether it needs story coverage.

    Dropped requirements and unfilled template rows (still holding a
    placeholder) do not need coverage.
    """
    found: Dict[str, bool] = {}
    for line in text.splitlines():
        match = REQ_ROW.match(line) or REQ_HEADING.match(line)
        if match:
            found[match.group(1)] = "dropped" not in line.lower() and PLACEHOLDER not in line
    return found


def normalize_sprint_length(value: str) -> str:
    """'7' -> '7 days', '1' -> '1 day'; text such as '2 weeks' is kept."""
    value = value.strip()
    if value.isdigit():
        return f"{value} day" if value == "1" else f"{value} days"
    return value


def find_root(start: Path) -> Path:
    for directory in [start, *start.parents]:
        if (directory / CONFIG_NAME).is_file():
            return directory
    for directory in [start, *start.parents]:
        if (directory / ".git").exists():
            return directory
    return start


def load_config(root: Path) -> Optional[dict]:
    path = root / CONFIG_NAME
    if not path.is_file():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        raise SystemExit(f"error: {CONFIG_NAME} is not valid JSON: {error}")


def required_docs(config: dict) -> List[Tuple[str, Optional[str]]]:
    profile = config.get("profile", "standard")
    docs = {"lite": LITE_DOCS, "standard": STANDARD_DOCS, "strict": STRICT_DOCS}.get(profile, STANDARD_DOCS)
    result = list(docs)
    if config.get("ui"):
        result += UI_DOCS
    if config.get("brief"):
        result += BRIEF_DOCS
    if config.get("assessment"):
        result += ASSESSMENT_DOCS
    seen: Dict[str, Optional[str]] = {}
    for path, template in result:
        seen.setdefault(path, template)
    return list(seen.items())


def read(root: Path, relative: str) -> Optional[str]:
    path = root / relative
    return path.read_text(encoding="utf-8") if path.is_file() else None


def docs_index(docs: Sequence[Tuple[str, Optional[str]]], existing: str = "") -> str:
    """Build docs/README.md from the profile's documents.

    Statuses already set in `existing` are kept, and rows the owner added for
    other documents are kept after the generated ones.
    """
    kept: Dict[str, str] = {}
    extra: List[str] = []
    listed = {path for path, _ in docs}
    for line in existing.splitlines():
        row = re.match(r"^\|\s*\[([^\]]+)\]\([^)]*\)\s*\|\s*([^|]+?)\s*\|", line)
        if not row:
            continue
        if row.group(1) in listed:
            kept[row.group(1)] = row.group(2)
        else:
            extra.append(line)
    lines = [
        "# Documentation",
        "",
        'Every document listed here exists and describes what exists. Status is "written" or "to be written"; keep it truthful.',
        "",
        "| Document | Status |",
        "|----------|--------|",
    ]
    for path, _ in docs:
        if path == INDEX_PATH:
            continue
        link = path[len("docs/"):] if path.startswith("docs/") else f"../{path}"
        lines.append(f"| [{path}]({link}) | {kept.get(path, 'to be written')} |")
    lines += extra
    return "\n".join(lines) + "\n"


